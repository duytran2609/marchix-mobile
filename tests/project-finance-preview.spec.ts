import { test } from './helpers/startupReminder';
import { expect } from '@playwright/test';

const previewUrl = process.env.MARCHIX_PREVIEW_URL ?? 'http://localhost:8081';

test('Chốt dự toán dự án và lập đề nghị chi theo mã khoản', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(previewUrl);
  await page.getByRole('button', { name: 'Đăng nhập quản trị (mô phỏng)' }).click();
  await page.getByRole('button', { name: 'Mở menu' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Dự án', exact: true }).click();
  await page.getByRole('button', { name: /^Chọn dự án:/ }).click();
  await page.getByRole('radio', { name: 'Marchix Mobile · Demo', exact: true }).click();
  await page.getByRole('tab', { name: 'Tài chính', exact: true }).click();
  const finance = page.getByRole('region', { name: 'Tài chính', exact: true });
  await finance.getByRole('button', { name: '+ Thuê / trả trước / cọc' }).click();
  const rent = page.getByRole('dialog', { name: 'Thuê / trả trước / cọc' });
  await expect(rent.getByRole('textbox', { name: 'Tiền thuê mỗi tháng (VNĐ)' })).toBeVisible();
  await expect(rent.getByRole('button', { name: 'Hủy', exact: true })).toHaveCount(0);
  await rent.getByRole('button', { name: 'Đóng biểu mẫu' }).click();
  await expect(rent).toBeHidden();
  await finance.getByRole('button', { name: '+ Khoản dự toán' }).click();
  const budget = page.getByRole('dialog', { name: 'Lập khoản dự toán' });
  await budget.getByRole('textbox', { name: 'Mua / chi gì?' }).fill('Thiết bị demo');
  const category = budget.getByRole('button', { name: /^Hạng mục:/ });
  const background = await category.evaluate(item => getComputedStyle(item).backgroundColor);
  await category.click();
  await page.getByRole('radio', { name: 'Thiết bị dự án', exact: true }).click();
  await expect(category).toHaveCSS('background-color', background);
  await expect(budget.getByRole('button', { name: 'Hủy', exact: true })).toHaveCount(0);
  await budget.getByRole('textbox', { name: 'Số tiền tổng (VNĐ)' }).fill('100000');
  const save = budget.getByRole('button', { name: 'Ghi lại dự toán' });
  await expect(save.locator('..')).toHaveCSS('border-top-width', '0px');
  await save.click();
  await expect(budget).toBeHidden();
  await expect(finance.getByText('Đã ghi khoản dự toán.')).toBeVisible();
  const closeBudget = finance.getByRole('button', { name: /^Chốt (dự toán|điều chỉnh)$/ });
  const item = finance.getByText('Thiết bị demo', { exact: true });
  await item.locator('..').getByRole('button', { name: /^Sửa DT/ }).click();
  const edit = page.getByRole('dialog', { name: 'Sửa khoản dự toán' });
  await edit.getByRole('button', { name: 'Bỏ khoản khỏi bản nháp' }).click();
  const remove = page.getByRole('dialog', { name: 'Bỏ khoản khỏi bản nháp' });
  await expect(remove.getByRole('button', { name: 'Hủy', exact: true })).toHaveCount(0);
  await remove.getByRole('button', { name: 'Đóng biểu mẫu' }).click();
  await expect(edit.getByRole('textbox', { name: 'Mua / chi gì?' })).toHaveValue('Thiết bị demo');
  await edit.getByRole('button', { name: 'Đóng biểu mẫu' }).click();
  expect((await closeBudget.boundingBox())!.y).toBeGreaterThan((await item.boundingBox())!.y);
  await closeBudget.click();
  const reason = finance.getByRole('textbox', { name: 'Lý do điều chỉnh' });
  if (await reason.isVisible()) await reason.fill('Bổ sung thiết bị demo');
  await finance.getByRole('button', { name: 'Xác nhận chốt dự toán' }).click();
  await expect(finance.getByText('Đã chốt dự toán.')).toBeVisible();
  for (const label of ['Thuế, báo giá, cọc & phân tích', 'Dòng tiền 13 tuần & hòa vốn']) {
    const disclosure = finance.getByRole('button', { name: label, exact: true });
    await expect(disclosure).toHaveAttribute('aria-expanded', 'false');
    await expect(disclosure).toContainText('▾');
    await disclosure.click();
    await expect(disclosure).toHaveAttribute('aria-expanded', 'true');
    await expect(disclosure).toContainText('▴');
    await disclosure.click();
    await expect(disclosure).toHaveAttribute('aria-expanded', 'false');
  }
  const newLine = finance.getByRole('button', { name: /^Đề nghị chi · DT/ }).last();
  const code = (await newLine.innerText()).split(' · ')[1];
  await newLine.click();
  await expect(page.getByRole('heading', { name: 'Đề nghị chi dự án' })).toBeVisible();
  const expense = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: 'Đề nghị chi dự án' }) });
  await expect(expense.getByRole('button', { name: /^Dự án:/ })).toHaveCount(0);
  await expect(expense.getByRole('button', { name: 'Hủy', exact: true })).toHaveCount(0);
  await expect(page.getByRole('textbox', { name: 'Mã khoản dự toán' })).toHaveValue(code);
  await expect(page.getByRole('textbox', { name: 'Nội dung' })).toHaveValue('Thiết bị demo');
  await expense.getByRole('button', { name: 'Nhóm hạng mục: Triển khai' }).click();
  const groups = page.getByRole('radiogroup', { name: 'Nhóm hạng mục' }).getByRole('radio');
  await expect(groups).toHaveText(['Chuẩn bị', 'Triển khai', 'Bàn giao']);
  await groups.filter({ hasText: 'Triển khai' }).click();
  await expense.getByRole('button', { name: /^Hạng mục:/ }).click();
  await page.getByRole('radio', { name: 'Thiết bị dự án', exact: true }).click();
  await page.getByRole('button', { name: 'Gửi khoản chi' }).click();
  await page.getByRole('button', { name: 'Về tài chính dự án' }).click();
  await expect(finance.getByText('Thiết bị demo', { exact: true }).last()).toBeVisible();
  await expect(finance.getByText(new RegExp('^Chờ duyệt · .* · ' + code + '$'))).toBeVisible();
});

test('Dự toán giữ số tiền và chi tiết khi đổi chế độ nhập', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(previewUrl);
  await page.getByRole('button', { name: 'Đăng nhập quản trị (mô phỏng)' }).click();
  await page.getByRole('button', { name: 'Mở menu' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Dự án', exact: true }).click();
  await page.getByRole('button', { name: /^Chọn dự án:/ }).click();
  await page.getByRole('radio', { name: 'Marchix Mobile · Demo', exact: true }).click();
  await page.getByRole('tab', { name: 'Tài chính', exact: true }).click();
  const finance = page.getByRole('region', { name: 'Tài chính', exact: true });
  await finance.getByRole('button', { name: '+ Khoản dự toán' }).click();
  const budget = page.getByRole('dialog', { name: 'Lập khoản dự toán' });
  await budget.getByRole('textbox', { name: 'Mua / chi gì?' }).fill('Kiểm thử đổi chế độ dự toán');
  await budget.getByRole('button', { name: /^Hạng mục:/ }).click();
  await page.getByRole('radio', { name: 'Thiết bị dự án', exact: true }).click();
  await budget.getByRole('textbox', { name: 'Số tiền tổng (VNĐ)' }).fill('500000');
  await budget.getByRole('button', { name: 'Chi phí & VAT' }).click();
  await expect(budget.getByRole('textbox', { name: 'Mua / chi gì?' })).toHaveCount(0);
  await expect(budget.getByRole('textbox', { name: 'Đơn giá (VNĐ)', exact: true })).toHaveValue('500000');
  const quantity = budget.getByRole('textbox', { name: 'Số lượng', exact: true });
  await quantity.fill('2,5');
  await budget.getByRole('button', { name: 'Tăng số lượng', exact: true }).click();
  await expect(quantity).toHaveValue('3,5');
  await budget.getByRole('button', { name: 'Giảm số lượng', exact: true }).click();
  await expect(quantity).toHaveValue('2,5');
  await quantity.fill('2');
  await budget.getByRole('button', { name: 'Báo giá & dự báo' }).click();
  await expect(quantity).toHaveCount(0);
  await budget.getByRole('textbox', { name: 'Căn cứ báo giá', exact: true }).fill('Báo giá kiểm thử');
  await budget.getByRole('button', { name: 'Thông tin chính' }).click();
  await expect(budget.getByRole('textbox', { name: 'Số tiền tổng (VNĐ)' })).toHaveValue('1.000.000');
  await expect(budget.getByRole('textbox', { name: 'Số tiền tổng (VNĐ)' })).toBeEditable();
  await budget.getByRole('button', { name: 'Ghi lại dự toán' }).click();
  await expect(budget).toBeHidden();
  await expect(finance.getByText('Đã ghi khoản dự toán.')).toBeVisible();
  await finance.getByRole('button', { name: /^Sửa DT/ }).last().click();
  const edit = page.getByRole('dialog', { name: 'Sửa khoản dự toán' });
  await expect(edit.getByRole('textbox', { name: 'Mua / chi gì?' })).toHaveValue('Kiểm thử đổi chế độ dự toán');
  await expect(edit.getByRole('textbox', { name: 'Số tiền tổng (VNĐ)' })).toHaveValue('1.000.000');
  await edit.getByRole('button', { name: 'Chi phí & VAT' }).click();
  await expect(edit.getByRole('textbox', { name: 'Số lượng', exact: true })).toHaveValue('2');
  await expect(edit.getByRole('textbox', { name: 'Đơn giá (VNĐ)', exact: true })).toHaveValue('500.000');
  await edit.getByRole('button', { name: 'Báo giá & dự báo' }).click();
  await expect(edit.getByRole('textbox', { name: 'Căn cứ báo giá', exact: true })).toHaveValue('Báo giá kiểm thử');
  await edit.getByRole('button', { name: 'Đóng biểu mẫu' }).click();

  await finance.getByRole('button', { name: 'Dòng tiền 13 tuần & hòa vốn', exact: true }).click();
  const openForecast = finance.getByRole('button', { name: 'Nhập dòng tiền & hòa vốn' });
  const forecast = page.getByRole('dialog', { name: 'Nhập dòng tiền 13 tuần & hòa vốn' });
  await openForecast.click();
  await expect(forecast.getByRole('button', { name: 'Hủy', exact: true })).toHaveCount(0);
  const saveForecast = forecast.getByRole('button', { name: 'Ghi lại dòng tiền' });
  await expect(saveForecast).toBeInViewport({ ratio: 1 });
  await expect(saveForecast.locator('..')).toHaveCSS('border-top-width', '0px');
  await expect(saveForecast.getByText('Ghi lại dòng tiền')).toHaveCSS('font-weight', '500');
  await expect(saveForecast.getByText('Ghi lại dòng tiền')).toHaveCSS('text-transform', 'none');
  const saveY = (await saveForecast.boundingBox())!.y;
  await forecast.getByRole('textbox', { name: 'Tiền đầu kỳ (VNĐ)' }).fill('500000');
  await forecast.getByRole('textbox', { name: 'Thu tuần 13 (VNĐ)', exact: true }).fill('200000');
  await expect(forecast.getByRole('textbox', { name: 'Tiền đầu kỳ (VNĐ)' })).not.toBeInViewport();
  expect((await saveForecast.boundingBox())!.y).toBeCloseTo(saveY);
  await saveForecast.click();
  await expect(forecast).toBeHidden();
  await expect(finance.getByText('Đã ghi dự báo dòng tiền.')).toBeVisible();
  await openForecast.click();
  await expect(forecast.getByRole('textbox', { name: 'Tiền đầu kỳ (VNĐ)' })).toHaveValue('500000');
  await expect(forecast.getByRole('textbox', { name: 'Thu tuần 13 (VNĐ)', exact: true })).toHaveValue('200000');
  await forecast.getByRole('button', { name: 'Đóng biểu mẫu' }).click();
  await expect(forecast).toBeHidden();
});
